/**
 * 折叠屏判据（纯函数，零依赖）—— **全站唯一真源**。
 *
 * 前端 `src/lib/catalog.ts` 从这里引（2026-10-16 起唯一消费者；
 * 原构建期 `scripts/sprite/generate.mjs` 随去像素化退役，已删除）。
 *
 * 为什么要单独抽一个文件
 * ----------------------
 * 判据曾经有两份，两份都不全：
 *
 *   - 前端 catalog.ts：官网原文含「折叠/展开」二字 → 对（7 台）
 *   - sprite generate.mjs：`sizeIn >= 7.5 || line 匹配 x\d` → 错（4 台）
 *
 * 两份判据不一致的后果不是「某个数字不好看」，而是**用户看到的形态标签和立绘互相打脸**：
 * 机型库标着「折叠屏」，首页立绘却画成一块直板砖。
 *
 * 而且它是**静默**的：sprite 的 layout() 返回的数仍是合法数字，
 * 单测抓不到、产物闸门抓不到、像素风扫描也抓不到。
 * 这个分歧是2026-10-06 新增 `scripts/sprite/review.mjs`（按几何分组排立绘，
 * 该脚本已随 2026-10-16 去像素化退役删除）之后肉眼发现的 ——
 * 审查表里「折叠档混进直板机」一眼可见。
 *
 * 三个坑，每一个都是实测踩出来的
 * ----------------------------
 * 1. **不用 `body.folded`**：该字段在实测 60 台上**全是 null**（两家适配器都没填），
 *    拿恒为 null 的字段当判据 = 折叠屏全被判成直板手机，且零报错。
 *    这是「类型声明看起来能用、运行时是空壳」那类静默失效。
 * 2. **不用「折叠态/展开态」这种带「态」字的写法**：第一版就是这么写的，
 *    结果 Mate X6 / Mate X7 被漏判 —— 华为这两台的官网原文写的是
 *    `折叠：73.78 mm | 展开：144.04 mm`，**没有「态」字**，而 Mate XT 写的是「折叠态」。
 *    同一家的两批页面用两种措辞，正则按一家的一种措辞写就必然漏。
 *    **教训：判据要落在「语义不可再分」的最小单位上（这里就是「折叠」二字），
 *    而不是落在某页面的具体句式上。**
 * 3. **不用任何尺寸/厚度阈值**（`sizeIn >= 7.5`、`厚度 > 10mm` 这类）：
 *    那是在拿数据反推形态，属于**估算**。两个实测反例：
 *      - Pura X 主屏 6.3 英寸、展开态厚 7.15mm —— 阈值判据会漏判；
 *      - 反过来 8 英寸平板会被 `sizeIn>=7.5` 误判成折叠机。
 *    **官网写了折叠就说明它折叠。**
 *
 * 已知漏判：`HUAWEI Pura X View` 官网尺寸段只有 `144.1 mm | 87.0 mm | 6.68 mm`，
 * 没写折叠/展开。它实际是折叠机型，但**官网原文没给判据** —— 按数据诚信原则
 * 不猜、不按机型名反推，计入直板。如哪天原文补上，这里自动改判。
 *
 * 反向测过：直板对照组（iPhone 16 / 18 Pro、Mate 90、畅享 90、nova 16 Ultra、
 * Mate 70 Air）的尺寸段一律不含这两个字，不会误判成折叠屏。
 */

/**
 * @param {{category?: string, rawOfficial?: Record<string, unknown>}} p
 * @returns {boolean}
 */
export function isFoldableOfficial(p) {
  // 「折叠」是**手机的形态维度**，不是任何品类的通用词。路由器官网写「天线折叠/直立两种形态」、
  // 折叠桌椅写「折叠尺寸」，这些原文里都有「折叠」二字 —— 不加品类门禁，它们会被判成折叠屏，
  // 2026-10-27 华为路由补全后真实发生过（selftest「折叠屏必须全部落在 phone 品类里」报红）。
  // 品类缺失（旧快照 / 测试夹具）按 phone 处理，与 categoryOf 的回退口径一致。
  if (p?.category && p.category !== 'phone') return false;
  const dims = p?.rawOfficial?.['尺寸与重量'];
  const text = typeof dims === 'string' ? dims : '';
  return /折叠|展开/.test(text);
}