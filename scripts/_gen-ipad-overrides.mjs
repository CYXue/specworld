/**
 * 一次性生成脚本：苹果 iPad 全代（2010 初代 – 2025 M5，共 41 台）
 * 以 add-product 条目写入 data/overrides.json（op 追加到现有 entries 之后）。
 *
 * 产品线：主线 10（iPad 1–10）/ mini 7 / Air 9（Air 6·7 分 11/13 双尺寸）/
 *         Pro 15（11 与 12.9/13 分代，M4/M5 为 11+13 双机）。
 *
 * 数据纪律（与 _gen-iphone-overrides.mjs 同一红线）：
 *   - 只录**苹果官网口径**；官网不公布一律不写键（iPad RAM、老机型亮度、
 *     蜂窝版 GPS 细节、mini/air 的 IP 等级等全部 unknown）；
 *   - 单位用官网口径：电池 Wh、重量 g、尺寸高×宽×厚 mm；
 *   - 中高置信才录，没有把握的留空。生成源可复跑（幂等：先剔除本脚本旧条目再追加）。
 *
 * 跑完必须过闸门：npm run selftest && npm run data
 */
import { readFileSync, writeFileSync } from 'node:fs';

const OVERRIDES = new URL('../data/overrides.json', import.meta.url);
const D = '2026-10-15';
const BY = '同志';
const MARK = 'gen-ipad-batch';

/** 读现有 overrides，剔除本脚本旧条目（幂等重跑），续接 id 序号 */
const store = JSON.parse(readFileSync(OVERRIDES, 'utf8'));
const kept = (store.entries ?? []).filter((e) => !String(e.id).includes(MARK));
const startSeq = kept.length;

const entries = [];
let seq = startSeq;

function pad({ id, name, date, status, specs }) {
  seq += 1;
  entries.push({
    id: `ovr-${MARK}-${String(seq - startSeq).padStart(3, '0')}`,
    op: 'add-product',
    createdAt: D,
    product: {
      id,
      slug: id,
      brand: 'apple',
      category: 'tablet',
      line: 'iPad',
      name,
      nameZh: null,
      releaseDate: date,
      releaseDatePrecision: 'day',
      status: status ?? 'discontinued',
      retiredAt: null,
      skus: [],
      scores: [],
      granularity: 'manual',
      specs,
      // provenance：object 型字段（resolutionPx）的子路径也要登记（validate 硬闸门）
      provenance: {
        ...Object.fromEntries(Object.keys(specs).map((k) => [k, 'user-manual'])),
        releaseDate: 'user-manual',
        ...(specs['display.resolutionPx']
          ? {
              'display.resolutionPx.w': 'user-manual',
              'display.resolutionPx.h': 'user-manual',
            }
          : {}),
      },
      notes: [],
    },
    reason: '苹果 iPad 全代收录（管线仅覆盖 iPhone 规格页与对比页矩阵，iPad 无自动通道）——按官网技术规格人工核查补录，官网未公布的字段留空',
    source: 'user-manual',
    sourceUrl: null,
    createdBy: BY,
    active: true,
  });
}

const res = (w, h) => ({ w, h });
const rear = (role, mp, aperture, ois, sensorNote) => ({
  role,
  mp,
  aperture: aperture ?? null,
  ois: ois ?? null,
  sensorNote: sensorNote ?? null,
});
const front = (mp, aperture) => ({ mp: mp ?? null, aperture: aperture ?? null });
const GB = (a) => a;

