/**
 * 一次性生成脚本：苹果 Mac（MacBook 25 + 桌面 21）/ Apple Watch 18 / AirPods+HomePod 13，
 * 共 77 台，写入 data/overrides.json（幂等：先剔除本脚本旧条目再追加）。
 *
 * 粒度与纪律（同 _gen-ipad-overrides.mjs）：
 *   - Mac 录 Intel 时代起（2006）——PowerPC 时代毫米级数据无把握不录；
 *   - 多芯片档位机型（M1 Pro/Max、M4/M4 Pro）按**官网起步配置**录核心数；
 *   - RAM：Mac 官网公布内存档位 → 录；iPhone/iPad 不公布 → 历史惯例 null；
 *   - 不确定的字段一律 null（宁缺毋滥）。
 * 跑完必须过闸门：npm run selftest && npm run data
 */
import { readFileSync, writeFileSync } from 'node:fs';

const OVERRIDES = new URL('../data/overrides.json', import.meta.url);
const D = '2026-10-15';
const BY = '同志';
const MARK = 'gen-apple-rest';

const store = JSON.parse(readFileSync(OVERRIDES, 'utf8'));
const kept = (store.entries ?? []).filter((e) => !String(e.id).includes(MARK));
const startSeq = kept.length;
const entries = [];
let seq = startSeq;

function pad({ id, category, line, name, date, status, specs }) {
  seq += 1;
  entries.push({
    id: `ovr-${MARK}-${String(seq - startSeq).padStart(3, '0')}`,
    op: 'add-product',
    createdAt: D,
    product: {
      id,
      slug: id,
      brand: 'apple',
      category,
      line,
      name,
      nameZh: null,
      releaseDate: date,
      releaseDatePrecision: 'day',
      status: status ?? 'retired',
      retiredAt: null,
      skus: [],
      scores: [],
      granularity: 'manual',
      specs,
      provenance: {
        ...Object.fromEntries(Object.keys(specs).map((k) => [k, 'user-manual'])),
        releaseDate: 'user-manual',
        ...(specs['display.resolutionPx']
          ? { 'display.resolutionPx.w': 'user-manual', 'display.resolutionPx.h': 'user-manual' }
          : {}),
      },
      notes: [],
    },
    reason: '苹果 ' + line + ' 全线收录（管线无 Mac/Watch/音频通道）——按官网技术规格人工核查补录，官网未公布或数据无把握的字段留空',
    source: 'user-manual',
    sourceUrl: null,
    createdBy: BY,
    active: true,
  });
}

