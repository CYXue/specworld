const OVERRIDES = 'data/overrides.json';
const D = '2026-10-15';
const BY = '同志';
const MARK = 'gen-apple-2026';

/** 读现有 overrides，剔除本脚本旧条目（幂等重跑），续接 id 序号 */
const store = JSON.parse(readFileSync(OVERRIDES, 'utf8'));
const kept = (store.entries ?? []).filter((e) => !String(e.id).includes(MARK));
const startSeq = kept.length;

const entries = [];
let seq = startSeq;

/**
 * add-product 条目。category/line 每品类显式传入（validate 硬闸门要求显式 category）。
 * provenance：object 型字段（resolutionPx）的子路径也要登记。
 */
