    - 彩虹弧：88px 高里七条弧各占1~2px，挤成彩色细线；
    - 太极图案本体（S 形曲线 + 鱼眼）：在横幅这个比例下
      「圆」会被压成椭圆，一眼就出戏 —— 只取它的**明度结构**。
  -->
