<script setup lang="ts">
/**
 * 黑白太极天空：**8 段离散色带**，中间最亮、上下暗。
 *
 * 为什么从彩虹改成黑白太极（用户 2026-10-06 提议）：
 * 彩虹七条弧在 88px 高的横幅里**每条只有 1~2px**，挤成一道彩色细线，
 * 而且要靠七种高饱和色与暗底对抗，视觉噪声远大于信息量。
 * 黑白太极只靠**明度**一条轴说话，在像素风里最稳。
 *
 * 明度序列（**WCAG 线性亮度**）：0.010 → 0.040 → 0.085 → 0.128 → **0.175** → 0.142 → 0.095 → 0.045
 *
 * - **必须在 WCAG 线性亮度空间等差，不能在 sRGB 百分比上等差**。
 *   我第一版按 sRGB 灰阶排（8%→20%→36%…），结果 `#080809` 与 `#141416`
 *   的**线性亮度只差 0.5%** —— 肉眼看不出那一档，等于白占一行。
 *   sRGB 的低亮度端被严重压缩，**视觉上的等差在那里不成立**。
 *   自测里「相邻档明度差 ≥ 8%」那条立刻抓到了这个。
 * - **峰值偏上（第 5 档）** —— 太极的两鱼沿斜对角交错（S 形），
 *   亮度峰不在正中。偏上才有那个味道，纯对称只是条灰带。
 * - **峰值不能太亮**：标题「参数世界」就压在这档上。
 *   线性 L 0.185 时对纯白只有 4.45:1（AA 差 0.05），
 *   压到 0.175 得 4.65:1，留一点余量。
 *
 * 全部 8 档：相邻线性亮度差 ≥ 3.0%（肉眼逐档可辨）、
 * 对纯白文字对比度 ≥ 4.65:1（WCAG AA 是 4.5:1）。
 *
 * 关键约束：**离散色带，不是渐变**（`CONVENTIONS.md` §2.5.1「零渐变」——
 * 连续过渡是插值，像素风是枚举）。
 */
const props = withDefaults(defineProps<{ height?: string }>(), {
  height: 'clamp(120px, 22vh, 220px)',
});

const BANDS = [
