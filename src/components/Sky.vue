  '#63646b', //  4/8  L12.8%
  '#73747b', //  5/8  L17.5% ← 最亮（偏上，呼应太极 S 形）
  '#686970', //  6/8  L14.2%
  '#56575d', //  7/8  L 9.6%
  '#3b3c40', //  8/8  L 4.5% 底·接地面
